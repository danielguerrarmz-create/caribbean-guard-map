#!/usr/bin/env node
// One-time aid: parses the Squarespace WXR export into per-page JSON so
// src/content/*.ts can be hand-authored from something structured instead
// of re-reading raw HTML. Re-run any time to refresh scripts/out/ after
// re-exporting the XML; output is gitignored, not a build input.
import { mkdirSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { loadPages, REPO_ROOT } from './lib/wxr.mjs';
import { extractSections, mergeTeamMembers } from './lib/sections.mjs';
import { collectImageUrls } from './lib/media-urls.mjs';

const OUT_DIR = path.join(REPO_ROOT, 'scripts', 'out');
const PAGES_DIR = path.join(OUT_DIR, 'pages');

mkdirSync(PAGES_DIR, { recursive: true });

const pages = loadPages();
let totalEmptyButtons = 0;
let totalMarqueesNeedingContent = 0;
const excludedImages = new Set();
let teamMembers = [];

for (const page of pages) {
  const sections = extractSections(page.contentHtml);

  const record = { slug: page.slug, title: page.title, link: page.link, sections };

  if (page.slug === 'team') {
    teamMembers = mergeTeamMembers(sections);
    record.members = teamMembers;
  }

  writeFileSync(path.join(PAGES_DIR, `${page.slug}.json`), JSON.stringify(record, null, 2) + '\n', 'utf8');

  for (const section of sections) {
    totalEmptyButtons += section.buttons.filter((b) => b.needsManualContent).length;
    if (section.marquee?.needsManualContent) totalMarqueesNeedingContent += 1;
  }

  const { excluded } = collectImageUrls(page.contentHtml);
  excluded.forEach((u) => excludedImages.add(u));

  console.log(`wrote scripts/out/pages/${page.slug}.json (${sections.length} sections)`);
}

const placeholderRoles = teamMembers.filter((m) => m.role.trim() === 'Description goes here');
const missingBio = teamMembers.filter((m) => !m.bioHtml.trim());

const notesContent = `# Extraction notes

Generated by \`scripts/extract-content.mjs\` from \`docs/source-material/Squarespace-Wordpress-Export-07-17-2026 (1).xml\`.
These are known gaps in the source export, not bugs in the extractor -- read this before authoring \`src/content/*.ts\` in step 5.

## Content that cannot be recovered from the export

- **${totalEmptyButtons} button block(s)** across all pages render with an empty \`<div class="sqs-block-content"></div>\` in the export -- no label or link anywhere in the file. These are Squarespace "website-component" (React-rendered) buttons whose config never made it into the static dump. Every one of these needs a hand-written label + link when building the content files (e.g. Donar's button, Home's "Únete" button).
- **${totalMarqueesNeedingContent} marquee/scrolling-text block(s)** (Vision page) are likewise empty in the export. The scrolling text needs to be re-authored from scratch -- check the live site for the actual copy.
- **The homepage hero video is not present anywhere in the XML** (\`video.squarespace-cdn.com\`: 0 occurrences) -- Squarespace's native video player resolves its URL client-side, invisible to static export analysis. It's since been recovered: the stream lives at an AES-128-encrypted HLS manifest (\`.../7abab123-3a68-44e3-b309-4beff323b12c/playlist.m3u8\`, found by capturing the real request in a browser Network tab), and \`scripts/download-media.mjs\` now downloads + remuxes it automatically via ffmpeg (\`-extension_picky 0 -map p:1 -c copy\`, needed because the byte-range segment URLs have no file extension, which trips ffmpeg's default segment allowlist). Already downloaded to \`media/video/homepage-hero-1920x1080.mp4\` (1920x1080, h264/aac, 412.4s, ~157MB).
- The Home page's "Instagram" section in the export is a set of static \`instagram.com/reel/<id>/embed/\` iframes, not a live feed -- reference only. Per plan.md.txt, step 4 replaces this with a live Behold.so feed.

## Team page data quality

- ${placeholderRoles.length} of ${teamMembers.length} team members still have Squarespace's literal placeholder text \`"Description goes here"\` as their role/short-description field: ${placeholderRoles.map((m) => m.name).join(', ')}. Needs real copy from the user before step 5.
${missingBio.length > 0 ? `- ${missingBio.length} team member(s) have no bio HTML at all: ${missingBio.map((m) => m.name).join(', ')}.` : `- All ${teamMembers.length} team members do have bio HTML from the accordion block (the gap above is only the short role tag, not the full bio).`}
- Two name-spelling mismatches between the carousel widget and the accordion bios were auto-reconciled by normalizing accents/punctuation during merge (Melissa Gonzalez/González, Hershell Lewis/Hershell Lewis.) -- double check these two entries render the intended name.

## Excluded assets

- ${excludedImages.size} image(s) resolve under a different Squarespace siteId (\`631899055f241153091de64b\` vs the real site's \`6658cf433f03af778644f50f\`) and were excluded as leftover/foreign stock assets:
${[...excludedImages].map((u) => `  - ${u}`).join('\n')}
`;

writeFileSync(path.join(OUT_DIR, 'EXTRACTION-NOTES.md'), notesContent, 'utf8');
console.log(`wrote scripts/out/EXTRACTION-NOTES.md`);
